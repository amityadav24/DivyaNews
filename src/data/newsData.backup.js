export const getNewsByCategory = (categoryId) => {
    if (!categoryId) return newsData;
    return newsData.filter(news => news.categoryId === categoryId);
};

export const getNewsById = (id) => {
    return newsData.find(news => news.id === parseInt(id));
};

export const getFeaturedNews = () => {
    return newsData.filter(news => news.featured);
};

export const getLatestNews = (limit = 6) => {
    return newsData.slice(0, limit);
};
